#!/usr/bin/env python3
"""Refresh the offline ISO 4217 catalog from the official maintenance agency.

Usage: python3 scripts/generate_currency_catalog.py [path/to/list-one.xml]
Then run dart format lib/core/constants/currencies.dart.
"""

from pathlib import Path
import sys
import urllib.request
import xml.etree.ElementTree as ET

SOURCE = (
    "https://www.six-group.com/dam/download/financial-information/"
    "data-center/iso-currrency/lists/list-one.xml"
)


def main():
    if len(sys.argv) > 1:
        data = Path(sys.argv[1]).read_bytes()
    else:
        with urllib.request.urlopen(SOURCE, timeout=30) as response:
            data = response.read()
    root = ET.fromstring(data)
    names = {}
    for entry in root.findall("./CcyTbl/CcyNtry"):
        code = entry.findtext("Ccy")
        if code:
            names[code] = " ".join(entry.findtext("CcyNm").split())
    if len(names) < 150 or names.get("BRL") != "Brazilian Real":
        raise ValueError("Unexpected ISO currency catalog; leaving output untouched")
    def literal(name):
        return "'" + name.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$") + "'"

    lines = [
        "// Generated by scripts/generate_currency_catalog.py. Do not edit.",
        f"// ISO 4217 current currencies and funds, published {root.attrib['Pblshd']}.",
        f"// Source: {SOURCE}",
        "// Names are the maintenance agency's English names, not UI translations.",
        "const Map<String, String> kCurrencyNames = {",
        *[f"  '{code}': {literal(name)}," for code, name in sorted(names.items())],
        "};",
        "",
    ]
    output = Path(__file__).resolve().parents[1] / "lib/core/constants/currencies.dart"
    output.write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
